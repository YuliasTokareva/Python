# в каких единицах вводить значения
print("Пожалуйста, вводите значения в указанных единицах измерения!")
print()
P = float(input("Введите давление в паскалях (Па): "))
print("Давление:", P, "Па")
V = float(input("Введите объём в кубических метрах (м³): "))
print("Объём:", V, "м³")
T = float(input("Введите температуру в кельвинах (K): "))
print("Температура:", T, "K")
# универсальная газовая постоянная
R = 8.314
print("Газовая постоянная R =", R, "Дж/(моль·К)")
# Считаем количество вещества
n = (P * V) / (R * T)
print()
print("--- РЕЗУЛЬТАТ ---")
print("Количество газа в молях: n =", n)
print("Ответ:", round(n, 4), "моль")  # округляем до 4 знаков после запятой, чтобы не было километровых чисел